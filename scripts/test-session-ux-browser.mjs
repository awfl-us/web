import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'

const server = await createServer({ server: { host: '127.0.0.1', port: 0 } })
await server.listen()
const url = 'http://127.0.0.1:' + server.httpServer.address().port + '/scripts/session-ux-browser.html'
let browser
try {
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}: {}) })
  const page = await browser.newPage({ viewport: {width:390,height:844} })
  await page.context().grantPermissions(['clipboard-read','clipboard-write'])
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(url)
  const input = page.getByRole('textbox',{name:'Message'})
  const send = page.getByRole('button',{name:'Send',exact:true})
  const click = name => page.getByRole('button',{name,exact:true}).click()
  await input.waitFor()
  await mkdir('test-results',{recursive:true})
  for (const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:844})
    await page.waitForTimeout(80)
    const box = await input.boundingBox()
    const main = await page.locator('[data-awfl-slot="conversation"]').boundingBox()
    assert.ok(box.width >= Math.min(270,main.width-30), 'input too narrow at '+width+': '+box.width)
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'horizontal overflow at '+width)
    for(const control of [send,page.getByRole('button',{name:'Stop',exact:true}),page.getByRole('combobox',{name:'Model',exact:true})]) {
      const rect = await control.boundingBox()
      assert.ok(rect.x>=0 && rect.x+rect.width<=width+1 && rect.height>=40,'control clipped at '+width+': '+JSON.stringify(rect))
    }
    console.log('viewport',width,'input',Math.round(box.width))
    await page.screenshot({path:'test-results/session-composer-'+width+'.png'})
  }
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('heading',{name:'Deployment results'}).waitFor()
  assert.equal(await page.getByRole('table').count(),1)
  assert.equal(await page.getByRole('link',{name:'documentation'}).getAttribute('href'),'https://example.com/docs')
  assert.equal(await page.getByRole('link',{name:'unsafe link'}).count(),0)
  assert.equal(await page.locator('[data-awfl-slot="markdown"] img').count(),0)
  assert.equal(await page.locator('[data-awfl-slot="markdown"] strong').count(),1)
  const calls = page.getByRole('button',{name:'2 tool calls 2/2 results recorded'})
  const command = page.getByRole('button',{name:'Run command result Recorded'})
  const read = page.getByRole('button',{name:'Read file result Recorded'})
  const unmatched = page.getByRole('button',{name:'Tool result Unmatched in this view'})
  assert.equal(await page.getByText('**Raw tool output**',{exact:true}).count(),0)
  await calls.click()
  assert.equal(await calls.getAttribute('aria-expanded'),'true')
  await page.getByText(/src\/example.ts/).first().waitFor()
  await calls.click()
  await command.click()
  assert.equal(await page.getByText('**Raw tool output**',{exact:true}).count(),1)
  assert.ok(await command.evaluate((e)=>e.closest('[data-awfl-slot="activity"]').compareDocumentPosition(document.querySelectorAll('[data-activity-kind="result"]')[1]) & Node.DOCUMENT_POSITION_FOLLOWING))
  await read.click()
  await page.getByText('file contents',{exact:true}).waitFor()
  await unmatched.click()
  await page.getByText('unmatched output',{exact:true}).waitFor()
  await click('Toggle activity')
  assert.equal(await page.locator('[data-awfl-slot="activity"]').count(),0)
  assert.equal(await page.getByText('**Raw tool output**',{exact:true}).count(),1)
  await click('Toggle activity')
  assert.equal(await page.locator('[data-awfl-slot="activity"]').count(),4)
  assert.equal(await page.locator('[data-awfl-slot="markdown"] .hljs-keyword').count(),1)
  assert.equal(await page.getByText('untouched code',{exact:true}).count(),1)
  await page.getByRole('button',{name:'Copy code',exact:true}).first().click()
  assert.equal((await page.evaluate(()=>navigator.clipboard.readText())).trim(),'const answer = 42;')
  await page.getByRole('button',{name:'Copy response',exact:true}).first().click()
  assert.ok((await page.evaluate(()=>navigator.clipboard.readText())).startsWith('## Deployment results'))
  await page.getByRole('button',{name:'Expand group',exact:true}).click()
  await page.getByText('Nested technical **text**',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Collapse group',exact:true}).click()
  await click('Toggle metadata')
  assert.equal(await page.getByText(/\$0\.05/).count(),0)
  await click('Toggle metadata')
  assert.equal(await page.getByText(/\$0\.05/).count(),1)
  await click('Toggle message style')
  assert.equal(await page.getByRole('heading',{name:'Deployment results'}).count(),0)
  assert.equal(await page.locator('[data-awfl-message-style="legacy"]').count(),1)
  await click('Toggle message style')
  await page.getByRole('heading',{name:'Deployment results'}).waitFor()
  await input.fill('first line')
  await input.press('Shift+Enter')
  await input.press('End')
  await input.type('second line')
  assert.equal(await input.inputValue(),'first line\nsecond line')
  await page.getByRole('combobox',{name:'Workflow fund'}).selectOption('2.5')
  await page.getByRole('combobox',{name:'Model',exact:true}).selectOption('short')
  await input.press('Enter')
  await page.waitForFunction(()=>document.querySelector('[data-testid="submissions"]').textContent.includes('second line'))
  assert.deepEqual(JSON.parse(await page.getByTestId('submissions').textContent()),{text:'first line\nsecond line',fund:2.5,model:'short',scope:'a'})
  assert.equal(await input.inputValue(),'')
  await click('Toggle failure')
  await input.fill('failed draft')
  await send.click()
  await page.getByText('Submission failed: fixture failure',{exact:true}).waitFor()
  assert.equal(await input.inputValue(),'failed draft')
  await click('Switch session')
  assert.equal(await input.inputValue(),'')
  await input.fill('session B draft')
  await click('Switch session')
  assert.equal(await input.inputValue(),'failed draft')
  await click('Toggle failure')
  await send.click()
  await input.fill('new draft during acknowledgement')
  await page.waitForFunction(()=>document.querySelector('[data-testid="submissions"]').textContent.includes('failed draft'))
  assert.equal(await input.inputValue(),'new draft during acknowledgement')
  await page.setViewportSize({width:1440,height:844})
  const root = page.locator('[data-awfl-slot="workspace"]')
  const bgBefore = await input.evaluate(e=>getComputedStyle(e.closest('form')).backgroundColor)
  await click('Toggle theme')
  const bgAfter = await input.evaluate(e=>getComputedStyle(e.closest('form')).backgroundColor)
  assert.notEqual(bgBefore,bgAfter)
  await click('Switch layout')
  assert.equal(await root.getAttribute('data-navigation'),'right')
  assert.ok((await page.locator('[data-awfl-slot="navigation"]').boundingBox()).x > (await page.locator('[data-awfl-slot="conversation"]').boundingBox()).x)
  assert.equal(await input.inputValue(),'new draft during acknowledgement')
  await page.screenshot({path:'test-results/session-alternate-preset.png'})
  await page.reload()
  await input.waitFor()
  assert.equal(await root.getAttribute('data-navigation'),'right')
  assert.equal(await input.inputValue(),'new draft during acknowledgement')
  await click('Reset appearance')
  assert.equal(await root.getAttribute('data-navigation'),'left')
  await click('Stop')
  await page.getByText('Idle',{exact:true}).waitFor()
  assert.deepEqual(errors,[])
  console.log('Composer viewport, multiline, submit, failure, draft, stop, theme/layout persistence passed')
} finally {
  await browser?.close()
  await server.close()
}
